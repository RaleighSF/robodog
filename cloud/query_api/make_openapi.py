"""Generate openapi.yaml from backends.OPERATIONS (the single source of truth).
The same spec is the agent's tool on Azure AI Foundry and on Amazon Bedrock."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from backends import OPERATIONS

DOCS = {
    "vitals_latest": "Latest key vitals per robot: battery, posture, body height, hottest joint, tilt, link, edge health, and data age.",
    "vitals_snapshot": "Full latest vitals row per robot (every published field), for detailed questions.",
    "vitals_series": "Vitals over time (battery, detector rate, hottest joint temperature).",
    "motors_latest": "Latest state of all 12 joint motors: temperature, estimated torque, position, velocity, lost frames.",
    "motors_series": "Joint temperature and torque over time, per joint.",
    "posture_timeline": "When the robot changed posture (standing, low/sitting, lying).",
    "detections_summary": "Objects detected by the vision pipeline, by class, with average confidence.",
    "alerts_recent": "Recent alerts such as PPE violations.",
    "commands_recent": "Recent robot commands and whether they succeeded.",
    "overwatch_findings": "Current health findings with severity (high/medium/low): overheating joints, low battery, tilt, link loss, stale telemetry, PPE.",
}
paths = {}
for op, (fn, params) in OPERATIONS.items():
    route = "/" + op.replace("_", "/", 1)
    paths[route] = {"get": {
        "operationId": op,
        "summary": DOCS.get(op, fn),
        "parameters": [{"name": k, "in": "query", "required": False,
                        "description": "Timespan like 15m, 1h, 7d", "schema": {"type": "string", "default": v, "pattern": "^[0-9]{1,4}[smhd]$"}}
                       for k, v in params.items()],
        "responses": {"200": {"description": "Rows", "content": {"application/json": {"schema": {
            "type": "object", "properties": {"operation": {"type": "string"}, "rows": {"type": "array", "items": {"type": "object"}}}}}}},
            "400": {"description": "Invalid parameter"}, "502": {"description": "Query failed"}},
        "security": [{"apiKey": []}],
    }}
spec = {
    "openapi": "3.0.3",
    "info": {"title": "Watch Dog telemetry query API", "version": "1.1.0",
             "description": "Read-only telemetry for a Unitree Go2 robot dog. Cloud-neutral contract (ADR 0002); identical on Azure and AWS. It cannot command the robot."},
    "servers": [{"url": "{baseUrl}", "variables": {"baseUrl": {"default": "https://REPLACE-ME/api"}}}],
    "paths": paths,
    "components": {"securitySchemes": {"apiKey": {"type": "apiKey", "in": "header", "name": "x-functions-key",
        "description": "Azure Functions key; the AWS build uses its own API key header (see cloud/PARITY.md)."}}},
}
out = os.path.join(os.path.dirname(__file__), "openapi.yaml")
with open(out, "w") as f:
    f.write("# GENERATED by make_openapi.py from backends.OPERATIONS - do not edit by hand.\n")
    f.write(json.dumps(spec, indent=2))      # JSON is valid YAML
print("wrote", out, "with", len(paths), "operations")
